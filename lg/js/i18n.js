var Lang = {
  cur: 'en',
  list: ['en', 'es', 'ru'],
  set: function (code) { this.cur = I18N[code] ? code : 'en'; },
  // «auto» и пусто — язык системы, если он поддерживается, иначе английский
  resolve: function (pref) {
    if (I18N[pref]) return pref;
    var sys = String(navigator.language || 'en').toLowerCase().slice(0, 2);
    return I18N[sys] ? sys : 'en';
  },
  // «5 каналов» / «5 canales» / «5 channels»
  count: function (n) {
    if (this.cur === 'ru') {
      var m10 = n % 10, m100 = n % 100;
      var w = (m10 === 1 && m100 !== 11) ? 'канал'
        : (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) ? 'канала' : 'каналов';
      return n + ' ' + w;
    }
    if (this.cur === 'es') return n + (n === 1 ? ' canal' : ' canales');
    return n + (n === 1 ? ' channel' : ' channels');
  }
};

function t(key, vars) {
  var s = (I18N[Lang.cur] && I18N[Lang.cur][key]) || I18N.en[key] || key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, function (_, k) { return vars[k] != null ? vars[k] : ''; });
  }
  return s;
}
